/**
 * The key shape, derived from English with the string literals widened.
 *
 * Without the widening, `as const` would make every English value its own
 * literal type and no translation could ever be assigned. With it, the other
 * dictionaries are checked structurally: a missing key or a misspelled section
 * is a compile error rather than a blank label at runtime.
 */
type Widened<T> = {
  [K in keyof T]: T[K] extends string ? string : T[K] extends object ? Widened<T[K]> : T[K];
};

export type TranslationSchema = Widened<typeof en>;

/**
 * Every language file must supply every key. Completeness is enforced rather
 * than optional, because a half-translated interface is worse than an
 * untranslated one — the user cannot tell whether they are missing something.
 */
export type Dictionary = TranslationSchema;
